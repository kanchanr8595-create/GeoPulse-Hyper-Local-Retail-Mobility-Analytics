-- GeoPulse: Source Loading and Row Count Reconciliation
-- Database: GEOPULSE_DB
-- Schema: PUBLIC

-- 1. Verify GPS source-table row count
SELECT
    COUNT(*) AS TOTAL_GPS_RECORDS
FROM GEOPULSE_DB.PUBLIC.RAW_GPS_PINGS;

-- 2. Verify store source-table row count
SELECT
    COUNT(*) AS TOTAL_STORE_RECORDS
FROM GEOPULSE_DB.PUBLIC.RAW_STORE_LOCATIONS;

-- 3. Reconcile both source-table counts
SELECT
    'RAW_GPS_PINGS' AS SOURCE_TABLE,
    COUNT(*) AS CURRENT_ROW_COUNT
FROM GEOPULSE_DB.PUBLIC.RAW_GPS_PINGS

UNION ALL

SELECT
    'RAW_STORE_LOCATIONS',
    COUNT(*)
FROM GEOPULSE_DB.PUBLIC.RAW_STORE_LOCATIONS;

-- 4. Check duplicate GPS Ping IDs
SELECT
    COUNT(*) AS TOTAL_RECORDS,
    COUNT(DISTINCT PING_ID) AS UNIQUE_PING_IDS,
    COUNT(*) - COUNT(DISTINCT PING_ID) AS DUPLICATE_PING_IDS
FROM GEOPULSE_DB.PUBLIC.RAW_GPS_PINGS;

-- 5. Check duplicate Store IDs
SELECT
    COUNT(*) AS TOTAL_RECORDS,
    COUNT(DISTINCT STORE_ID) AS UNIQUE_STORE_IDS,
    COUNT(*) - COUNT(DISTINCT STORE_ID) AS DUPLICATE_STORE_IDS
FROM GEOPULSE_DB.PUBLIC.RAW_STORE_LOCATIONS;

-- 6. Check missing key identifiers
SELECT
    'RAW_GPS_PINGS' AS SOURCE_TABLE,
    COUNT(*) AS TOTAL_RECORDS,
    COUNT_IF(PING_ID IS NULL) AS MISSING_IDS
FROM GEOPULSE_DB.PUBLIC.RAW_GPS_PINGS

UNION ALL

SELECT
    'RAW_STORE_LOCATIONS',
    COUNT(*),
    COUNT_IF(STORE_ID IS NULL)
FROM GEOPULSE_DB.PUBLIC.RAW_STORE_LOCATIONS;

-- 7. Check GPS CSV loading history
SELECT
    TABLE_NAME,
    FILE_NAME,
    STATUS,
    ROW_COUNT,
    ROW_PARSED,
    FIRST_ERROR_MESSAGE
FROM TABLE(
    GEOPULSE_DB.INFORMATION_SCHEMA.COPY_HISTORY(
        TABLE_NAME => 'GEOPULSE_DB.PUBLIC.RAW_GPS_PINGS',
        START_TIME => DATEADD(DAY, -14, CURRENT_TIMESTAMP())
    )
)
ORDER BY LAST_LOAD_TIME DESC;

-- 8. Check store CSV loading history
SELECT
    TABLE_NAME,
    FILE_NAME,
    STATUS,
    ROW_COUNT,
    ROW_PARSED,
    FIRST_ERROR_MESSAGE
FROM TABLE(
    GEOPULSE_DB.INFORMATION_SCHEMA.COPY_HISTORY(
        TABLE_NAME => 'GEOPULSE_DB.PUBLIC.RAW_STORE_LOCATIONS',
        START_TIME => DATEADD(DAY, -14, CURRENT_TIMESTAMP())
    )
)
ORDER BY LAST_LOAD_TIME DESC;
