-- GeoPulse: Store Coordinate Metadata Verification
-- Database: GEOPULSE_DB
-- Schema: PUBLIC
-- Table: RAW_STORE_LOCATIONS

-- 1. Verify total store records
SELECT COUNT(*) AS TOTAL_STORES
FROM GEOPULSE_DB.PUBLIC.RAW_STORE_LOCATIONS;

-- 2. View all store-location records
SELECT *
FROM GEOPULSE_DB.PUBLIC.RAW_STORE_LOCATIONS;

-- 3. Verify table structure
DESC TABLE GEOPULSE_DB.PUBLIC.RAW_STORE_LOCATIONS;

-- 4. Check missing store information
SELECT
    COUNT(*) AS TOTAL_RECORDS,
    COUNT_IF(STORE_ID IS NULL) AS MISSING_STORE_IDS,
    COUNT_IF(STORE_NAME IS NULL) AS MISSING_STORE_NAMES,
    COUNT_IF(LATITUDE IS NULL) AS MISSING_LATITUDES,
    COUNT_IF(LONGITUDE IS NULL) AS MISSING_LONGITUDES
FROM GEOPULSE_DB.PUBLIC.RAW_STORE_LOCATIONS;

-- 5. Check duplicate Store IDs
SELECT
    COUNT(*) AS TOTAL_RECORDS,
    COUNT(DISTINCT STORE_ID) AS UNIQUE_STORE_IDS,
    COUNT(*) - COUNT(DISTINCT STORE_ID) AS DUPLICATE_STORE_IDS
FROM GEOPULSE_DB.PUBLIC.RAW_STORE_LOCATIONS;

-- 6. Validate latitude and longitude ranges
SELECT
    COUNT(*) AS TOTAL_RECORDS,
    COUNT_IF(LATITUDE < -90 OR LATITUDE > 90)
        AS INVALID_LATITUDES,
    COUNT_IF(LONGITUDE < -180 OR LONGITUDE > 180)
        AS INVALID_LONGITUDES
FROM GEOPULSE_DB.PUBLIC.RAW_STORE_LOCATIONS;

-- 7. Map GPS records with store-coordinate metadata
SELECT
    G.NEAREST_STORE_ID,
    COUNT(*) AS GPS_RECORDS,
    S.STORE_NAME,
    S.LATITUDE,
    S.LONGITUDE
FROM GEOPULSE_DB.PUBLIC.RAW_GPS_PINGS G
LEFT JOIN GEOPULSE_DB.PUBLIC.RAW_STORE_LOCATIONS S
    ON G.NEAREST_STORE_ID = S.STORE_ID
GROUP BY
    G.NEAREST_STORE_ID,
    S.STORE_NAME,
    S.LATITUDE,
    S.LONGITUDE
ORDER BY G.NEAREST_STORE_ID;
