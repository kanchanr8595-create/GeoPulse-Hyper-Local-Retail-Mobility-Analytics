-- GeoPulse: Source Table Verification
-- Database: GEOPULSE_DB
-- Schema: PUBLIC

-- 1. Verify GPS source-table count
SELECT COUNT(*) AS TOTAL_GPS_RECORDS
FROM GEOPULSE_DB.PUBLIC.RAW_GPS_PINGS;

-- 2. Verify store source-table count
SELECT COUNT(*) AS TOTAL_STORE_RECORDS
FROM GEOPULSE_DB.PUBLIC.RAW_STORE_LOCATIONS;

-- 3. Combined source-table counts
SELECT 'RAW_GPS_PINGS' AS SOURCE_TABLE, COUNT(*) AS TOTAL_RECORDS
FROM GEOPULSE_DB.PUBLIC.RAW_GPS_PINGS
UNION ALL
SELECT 'RAW_STORE_LOCATIONS', COUNT(*)
FROM GEOPULSE_DB.PUBLIC.RAW_STORE_LOCATIONS;

-- 4. Verify source-table columns and data types
SELECT
    TABLE_NAME,
    COLUMN_NAME,
    DATA_TYPE,
    ORDINAL_POSITION
FROM GEOPULSE_DB.INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA = 'PUBLIC'
AND TABLE_NAME IN ('RAW_GPS_PINGS', 'RAW_STORE_LOCATIONS')
ORDER BY TABLE_NAME, ORDINAL_POSITION;

-- 5. Check missing key identifiers
SELECT
    'RAW_GPS_PINGS' AS SOURCE_TABLE,
    COUNT(*) AS TOTAL_RECORDS,
    COUNT_IF(PING_ID IS NULL) AS MISSING_IDS
FROM GEOPULSE_DB.PUBLIC.RAW_GPS_PINGS
UNION ALL
SELECT
    'RAW_STORE_LOCATIONS',
    COUNT(*),
    COUNT_IF(STORE_ID IS NULL)
FROM GEOPULSE_DB.PUBLIC.RAW_STORE_LOCATIONS;
