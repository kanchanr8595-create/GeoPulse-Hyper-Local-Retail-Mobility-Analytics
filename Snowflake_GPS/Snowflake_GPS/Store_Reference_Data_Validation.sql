# Store Reference Data Validation

-- Database: GEOPULSE_DB
-- Schema: PUBLIC
-- Table: RAW_STORE_LOCATIONS

-- 1. Review store reference data
```sql
SELECT
    STORE_ID,
    STORE_NAME,
    STORE_STATUS,
    LATITUDE,
    LONGITUDE,
    CATCHMENT_RADIUS_M
FROM GEOPULSE_DB.PUBLIC.RAW_STORE_LOCATIONS
ORDER BY STORE_ID;
```

-- 2. Validate coordinates and catchment radius
```sql
SELECT
    STORE_ID,
    LATITUDE,
    LONGITUDE,
    CATCHMENT_RADIUS_M,
    CASE
        WHEN LATITUDE BETWEEN -90 AND 90
         AND LONGITUDE BETWEEN -180 AND 180
         AND CATCHMENT_RADIUS_M = 500
        THEN 'VALID'
        ELSE 'REVIEW'
    END AS VALIDATION_STATUS
FROM GEOPULSE_DB.PUBLIC.RAW_STORE_LOCATIONS
ORDER BY STORE_ID;
```

-- 3. Verify store status distribution
```sql
SELECT
    STORE_STATUS,
    COUNT(*) AS STORE_COUNT
FROM GEOPULSE_DB.PUBLIC.RAW_STORE_LOCATIONS
GROUP BY STORE_STATUS
ORDER BY STORE_STATUS;
```

-- 4. Check duplicate store IDs
```sql
SELECT
    COUNT(*) AS TOTAL_RECORDS,
    COUNT(DISTINCT STORE_ID) AS UNIQUE_STORE_IDS,
    COUNT(*) - COUNT(DISTINCT STORE_ID) AS DUPLICATE_STORE_IDS
FROM GEOPULSE_DB.PUBLIC.RAW_STORE_LOCATIONS;
```
